/// The program as a CE block: raw bytes for now (proba.bin, not yet
/// disassembled into CE form); instructions become CE ops as they are
/// lifted:
/// The program as a CE block: raw bytes for now (proba.bin, not yet
/// disassembled into CE form); instructions become CE ops as they are
/// lifted:
///
///   z80 {
///     yield! binary
///     // later:  Z80.LD_B 0x10
///     //         Z80.LD_HL 0x4000
///     //         ...
///   }
let program: Z80Op list = z80 { yield! binary }

/// The assembled machine code (structure -> bytes). For a fully CE
/// program this equals the game image; the test compares it against
/// proba.bin to prove byte parity with the original.
let assembled: byte[] = Z80.assemble program

/// The index is relative to the image's actual load address. It is kept once
/// so runtime writes can invalidate any instructions lifted later.
let index = Z80.makeIndexAt 0x8000 program
